"""Writers for batch results: Markdown and CSV."""

from __future__ import annotations

import csv
import datetime as _dt
from typing import Iterable

from .batch import Result


def _summary(results: Iterable[Result]) -> str:
    items = list(results)
    total = len(items)
    succeeded = sum(1 for item in items if item.status == "ok")
    failed = total - succeeded
    return f"Total: {total} | Succeeded: {succeeded} | Failed: {failed}"


def write_markdown(results, path: str, template: str = "", endpoint: str = "", model: str = "") -> None:
    """Write batch results as a human-readable Markdown file."""
    items = list(results)
    lines: list[str] = []
    lines.append("# Batch Results")
    lines.append("")
    lines.append(f"Generated: {_dt.datetime.now().isoformat(timespec='seconds')}")
    if endpoint:
        lines.append(f"Endpoint: {endpoint}")
    if model:
        lines.append(f"Model: {model}")
    if template:
        lines.append(f"Template: {template}")
    lines.append(_summary(items))
    lines.append("")
    lines.append("## Results")
    lines.append("")
    for item in items:
        lines.append(f"### {item.index + 1}. {item.status.upper()}")
        lines.append("")
        lines.append("**Input:**")
        lines.append("")
        lines.append("```")
        lines.append(item.input)
        lines.append("```")
        lines.append("")
        if item.status == "ok":
            lines.append("**Output:**")
            lines.append("")
            lines.append("```")
            lines.append(item.output)
            lines.append("```")
            lines.append("")
            lines.append(f"- Duration: {item.duration_ms:.0f} ms")
            lines.append(f"- Model: {item.model}")
        else:
            lines.append("**Error:**")
            lines.append("")
            lines.append("```")
            lines.append(item.error)
            lines.append("```")
            lines.append("")
        lines.append("---")
        lines.append("")
    lines.append("_Generated by prompt-batch (Asdale Dynamics, LLC)_")
    lines.append("")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def write_csv(results, path: str) -> None:
    """Write batch results as a machine-readable CSV file."""
    items = list(results)
    fieldnames = ["index", "input", "output", "model", "endpoint", "duration_ms", "status", "error"]
    with open(path, "w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for item in items:
            writer.writerow(item.to_row())
